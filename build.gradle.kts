        maven("https://jitpack.io")
    }

    dependencies {
        classpath("com.android.tools.build:gradle:8.7.3")
        // CloudStream gradle plugin from JitPack. The GitHub workflow
        // builds it from source first (see .github/workflows/build.yml)
